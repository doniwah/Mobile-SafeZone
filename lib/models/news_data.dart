class NewsData {
  final String title;
  final String summary;
  final String content;
  final String date;
  final String author;
  final String imagePath;
  final String category;

  NewsData({
    required this.title,
    required this.summary,
    required this.content,
    required this.date,
    required this.author,
    required this.imagePath,
    required this.category,
  });
}
